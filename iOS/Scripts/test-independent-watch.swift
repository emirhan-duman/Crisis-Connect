import Foundation
import CryptoKit
import Security

@main struct IndependentWatchChecks {
    @MainActor static func main() throws {
        final class Disk: IndependentWatchJournalStorage {
            var saved: [IndependentWatchOperation] = []
            var fail = false
            func read() throws -> [IndependentWatchOperation] { saved }
            func write(_ rows: [IndependentWatchOperation]) throws { if fail { throw IndependentWatchError.invalid }; saved = rows }
        }
        func rejects(_ action: () throws -> Void) {
            do { try action(); fatalError("Expected rejection") } catch { }
        }
        let disk = Disk(), journal = try IndependentWatchJournal(storage: disk)
        let message = try journal.reserve(action: "shortMessage", subjectID: "contact", payload: "ciphertext")
        let reopened = try IndependentWatchJournal(storage: disk)
        precondition(reopened.entries == [message])
        rejects { _ = try reopened.reserve(action: "shortMessage", subjectID: "contact", payload: "second") }
        var preparedAgain = false
        rejects { _ = try reopened.reservePrepared(action: "shortMessage", subjectID: "contact") { _ in preparedAgain = true; return "new ciphertext" } }
        precondition(!preparedAgain)
        try reopened.reconcile(id: message.id, state: "read")
        try reopened.reconcile(id: message.id, state: "accepted")
        precondition(reopened.entries[0].state == "read")
        let start = try reopened.reserve(action: "startSOS", subjectID: "session", payload: "start")
        try reopened.reconcile(id: start.id, state: "accepted")
        rejects { _ = try reopened.reserve(action: "startSOS", subjectID: "other", payload: "start") }
        let stop = try reopened.reserve(action: "stopSOS", subjectID: "session", payload: "stop")
        try reopened.reconcile(id: stop.id, state: "accepted")
        let final = try IndependentWatchJournal(storage: disk)
        precondition(final.entries.count == 3 && final.entries[2].id == stop.id)
        rejects { _ = try final.reserve(action: "startSOS", subjectID: "session", payload: "start") }
        disk.fail = true
        rejects { _ = try final.reserve(action: "shortMessage", subjectID: "another", payload: "text") }
        precondition(final.entries.count == 3)
        disk.fail = false; disk.saved.append(disk.saved[0])
        rejects { _ = try IndependentWatchJournal(storage: disk) }

        let sharedDisk = Disk()
        let firstOwner = try IndependentWatchJournal(storage: sharedDisk)
        let secondOwner = try IndependentWatchJournal(storage: sharedDisk)
        let a = try firstOwner.reserve(action: "shortMessage", subjectID: "a", payload: "first")
        let b = try secondOwner.reserve(action: "shortMessage", subjectID: "b", payload: "second")
        try firstOwner.reconcile(id: a.id, state: "delivered")
        let sharedRestored = try IndependentWatchJournal(storage: sharedDisk)
        precondition(sharedRestored.entries.map(\.id) == [a.id, b.id])
        rejects { _ = try firstOwner.reserve(action: "shortMessage", subjectID: "b", payload: "duplicate") }
        // Cross-language signature vector: generated by CryptoKit, verified by Node's P-256 verifier.
        let key = P256.Signing.PrivateKey()
        let deviceID = "11111111-1111-4111-8111-111111111111"
        let publicKey = key.publicKey.derRepresentation.base64EncodedString()
        let payload = Data("{\"version\":1,\"ownerUid\":\"watchTestOwner\",\"deviceID\":\"\(deviceID)\",\"publicKey\":\"\(publicKey)\",\"scopes\":[\"shortMessage\",\"sos\"]}".utf8).base64EncodedString()
        let signature = try key.signature(for: Data((IndependentWatchIdentity.domain + payload).utf8)).derRepresentation.base64EncodedString()
        let vector = ["deviceID":deviceID,"publicKey":publicKey,"payload":payload,"signature":signature]
        try JSONSerialization.data(withJSONObject: vector, options: [.sortedKeys]).write(to: URL(fileURLWithPath: CommandLine.arguments[1]), options: .atomic)
        // The keychain services and file are unique to this test and are removed afterward.
        let testDevice = UUID().uuidString.lowercased()
        let service = "crisis.watch.journal.test." + testDevice
        let file = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("cc-watch-" + testDevice + ".enc")
        defer {
            try? FileManager.default.removeItem(at: file)
            for name in [service, "crisis.watch.request.v1." + testDevice] {
                SecItemDelete([kSecClass: kSecClassGenericPassword, kSecAttrService: name, kSecAttrAccount: "watch"] as CFDictionary)
            }
        }
        let identity = try IndependentWatchIdentity(deviceID: testDevice)
        let actualKey = try identity.publicKey()
        let proof = try identity.enrollment(ownerUid: "watchTestOwner")
        precondition(proof["publicKey"] == actualKey)
        let restoredKey = try IndependentWatchIdentity(deviceID: testDevice).publicKey()
        precondition(restoredKey == actualKey)
        let encrypted = IndependentWatchJournalFile(url: file, service: service)
        let diskJournal = try IndependentWatchJournal(storage: encrypted)
        let persisted = try diskJournal.reserve(action: "shortMessage", subjectID: "contact", payload: "private fixture")
        let diskReopened = try IndependentWatchJournal(storage: encrypted)
        precondition(diskReopened.entries == [persisted])
        var bytes = try Data(contentsOf: file)
        precondition(!String(decoding: bytes, as: UTF8.self).contains("private fixture"))
        bytes[bytes.count - 1] ^= 1
        try bytes.write(to: file, options: .atomic)
        rejects { _ = try IndependentWatchJournal(storage: encrypted) }
        print("PASS: device keychain restore, encrypted file restore and tamper rejection.")
        print("PASS: restore, uncertain-send guard, monotonic receipts, saved SOS stop, no session reuse, disk failure, corrupt history; CryptoKit vector exported.")
    }
}

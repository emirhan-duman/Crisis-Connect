package com.auralis.crisisconnect.muster

import org.junit.Assert.*
import org.junit.Test

class MusterQueueTest {
    @Test fun onlyAValidEventReceiptCanMarkAResponseSent() {
        val event = MusterEvent("alice", "factory", "drill", "stable-operation", "safe", "", 1000)
        val valid = org.json.JSONObject().put("ok", true).put("id", "drill").put("eventId", musterServerEventId(event.uid, event.operationId)).put("applied", false)
        assertTrue(acceptsMusterReceipt(200, valid, event))
        assertFalse(acceptsMusterReceipt(200, valid, event.copy(session = "other")))
        assertFalse(acceptsMusterReceipt(503, valid, event))
        assertFalse(acceptsMusterReceipt(200, org.json.JSONObject().put("ok", true), event))
        assertFalse(acceptsMusterReceipt(200, valid, event.copy(operationId = "another-operation")))
        valid.put("ok", "true"); assertFalse(acceptsMusterReceipt(200, valid, event))
    }
    @Test fun receiptHashesMatchBackendJsonStringifyForCustomUidCharacters() {
        // SHA256(JSON.stringify([uid, operationId])).slice(0,32), generated by Node crypto.
        assertEquals("315d16d5d9dc2e6323bb41046311fc39", musterServerEventId("alice", "stable-operation"))
        assertEquals("33b73e4d724ea83285d7aad5c0b2d7d4", musterServerEventId("alice/\"</>\u2028", "op\\/\n"))
        assertEquals("af5788c4fb08399b9b4384fdd7d055f6", musterServerEventId("\uD800", "op"))
    }

    private class Memory : MusterPersistence {
        val data = mutableMapOf<String, String>(); var fail = false
        override fun read(key: String) = data[key]
        override fun write(key: String, value: String): Boolean { if (fail) return false; data[key] = value; return true }
    }
    @Test fun persistsBeforeDeliveryAndRetainsStableEventAcrossRestart() {
        val memory = Memory(); val first = MusterQueue(memory)
        val event = first.enqueue("alice", "factory", "drill", "help", "Stair exit", 1000, "event-id")
        val restarted = MusterQueue(memory); val claimed = restarted.claim("alice", 1000)!!
        assertEquals(event.operationId, claimed.operationId); assertEquals(1000L, claimed.answeredAt)
        assertNull(restarted.claim("alice", 1001))
        restarted.finish(claimed, "pending", 2000, "connection")
        val retry = restarted.claim("alice", 200000)!!
        assertEquals(event.request().toString(), retry.request().toString())
        restarted.finish(retry, "sent", 200001, receiptEventId = musterServerEventId(retry.uid, retry.operationId))
        assertNull(restarted.claim("alice", 999999)); assertEquals("sent", MusterQueue(memory).entries("alice").single().state)
    }
    @Test fun keepsAccountsIsolatedWithoutDeletingAnOfflineAnswer() {
        val queue = MusterQueue(Memory())
        queue.enqueue("alice", "factory", "drill", "safe", "", 1000)
        queue.enqueue("bob", "factory", "drill", "help", "", 1001)
        assertEquals("bob", queue.claim("bob", 1002)!!.uid)
        assertEquals("alice", queue.claim("alice", 1002)!!.uid)
        assertTrue(queue.entries("unknown").isEmpty())
    }
    @Test fun permanentFailureRemainsVisibleAndCannotClaimDelivery() {
        val queue = MusterQueue(Memory()); queue.enqueue("alice", "factory", "drill", "safe", "", 1)
        val event = queue.claim("alice", 2)!!; queue.finish(event, "failed", 3, "http-403")
        assertEquals("failed", queue.entries("alice").single().state); assertNull(queue.claim("alice", 999999))
    }
    @Test fun refusesToAcknowledgeAnUnpersistedAnswerAndDoesNotEvictAtCapacity() {
        val memory = Memory(); val queue = MusterQueue(memory); memory.fail = true
        assertThrows(IllegalStateException::class.java) { queue.enqueue("alice", "factory", "drill", "safe", "", 1) }
        assertTrue(queue.entries("alice").isEmpty()); memory.fail = false
        repeat(256) { queue.enqueue("alice", "factory", "drill", "safe", "", it.toLong()) }
        assertThrows(IllegalStateException::class.java) { queue.enqueue("alice", "factory", "drill", "help", "", 999) }
        assertEquals(256, queue.entries("alice").size)
    }
}
